/// The two shipped posts and the extension of their golden programs.
const POSTS: [(&str, &str); 2] = [("makera-z1", "nc"), ("linuxcnc", "ngc")];

/// Where a sample's part comes from.
enum Model {
    /// A part generated by `openchuck-testkit`, meshed with this many
    /// stations along X and round the axis.
    Generated(Box<dyn RadialPart>, (u32, u32)),
    /// A model file in `testdata/`, with the X range it spans.
    File(&'static str, (f64, f64)),
}

impl Model {
    /// The X range the part spans.
    fn x_range(&self) -> (f64, f64) {
        match self {
            Self::Generated(part, _) => part.x_range(),
            Self::File(_, range) => *range,
        }
    }

    /// Writes the part as the STL file at `path`.
    fn write(&self, path: &Path) {
        match self {
            Self::Generated(part, mesh) => write_stl(part.as_ref(), *mesh, path).unwrap(),
            Self::File(file, _) => {
                let source = Path::new(env!("CARGO_MANIFEST_DIR"))
                    .join("../../testdata")
                    .join(file);
                std::fs::copy(source, path).unwrap();
            }
        }
    }
}

/// One sample project. The generated ones are the reference jobs
/// (`crates/openchuck-app/tests/reference_jobs.rs` builds the same jobs
/// through the application API; the golden programs tie the two together,
/// so a drift in either fails); `blisk` is the owner's part from a file
/// (OI-311).
struct Sample {
    name: &'static str,
    model: Model,
    /// The part's largest radius about the rotary axis.
    radius: f64,
    strategy: &'static str,
    parameters: Vec<(&'static str, ParameterValue)>,
    /// How far the stock runs past the part at each end, in millimetres.
    margin: f64,
    /// How much wider the stock is than the part's widest, in millimetres.
    oversize: f64,
    /// Workholding options of `openchuck-cli setup` (SET-09, OP-21).
    holding: Vec<&'static str>,
}

fn cone() -> Box<dyn RadialPart> {
    Box::new(sample_projects::cone())
}

fn angle_step(degrees: f64) -> Vec<(&'static str, ParameterValue)> {
    vec![("max_angle_step", ParameterValue::Number(degrees))]
}

fn sample(name: &'static str, part: Box<dyn RadialPart>, radius: f64) -> Sample {
    Sample {
        name,
        model: Model::Generated(part, (121, 144)),
        radius,
        strategy: "helical_finishing",
        parameters: angle_step(5.0),
        margin: 1.0,
        oversize: 2.0,
        holding: Vec::new(),
    }
}

fn blisk(
    name: &'static str,
    strategy: &'static str,
    parameters: Vec<(&'static str, ParameterValue)>,
) -> Sample {
    Sample {
        name,
        model: Model::File("stl/blisk.stl", (0.0, 50.0)),
        radius: 20.0,
        strategy,
        parameters,
        margin: 1.0,
        oversize: 2.0,
        holding: Vec::new(),
    }
}


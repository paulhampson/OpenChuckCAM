macro_rules! sample_tests {
    ($($name:ident),* ; no_simulation: $($bare:ident),* $(,)?) => {
        $(mod $name {
            #[test]
            fn req_gc_07_req_nfr_06_req_nfr_08_req_gc_11_runs_end_to_end_at_1_2_and_n_threads() {
                super::end_to_end(stringify!($name));
            }
            #[test]
            fn req_sim_03_req_sim_05_simulates_without_overcut() {
                super::simulates(stringify!($name));
            }
            #[test]
            fn req_gc_07_req_nfr_08_the_committed_project_writes_the_golden_programs() {
                super::committed(stringify!($name));
            }
        })*
        $(mod $bare {
            #[test]
            fn req_gc_07_req_nfr_06_req_nfr_08_req_gc_11_runs_end_to_end_at_1_2_and_n_threads() {
                super::end_to_end(stringify!($bare));
            }
        })*
        /// Every sample project has its tests above.
        const SAMPLE_TESTS: &[&str] = &[$(stringify!($name),)* $(stringify!($bare)),*];
    };
}


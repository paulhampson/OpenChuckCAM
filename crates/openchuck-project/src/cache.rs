//! Where generated data goes (PRJ-03).
//!
//! Toolpaths, simulation caches and G-code are never stored in the project
//! files; they are regenerated. Anything the application keeps between runs
//! lives in one cache folder inside the project folder. The folder carries its
//! own generated `.gitignore` that ignores everything in it, so Git and other
//! tools that read `.gitignore` skip it without the user's own ignore files
//! being touched.

use std::path::{Path, PathBuf};

use crate::error::ProjectError;

/// Name of the cache folder inside a project folder.
pub const CACHE_DIR: &str = ".openchuck-cache";

/// Contents of the generated ignore file in the cache folder.
pub const CACHE_IGNORE: &str = "# Generated by OpenChuckCAM. This folder holds regenerated data only; it is\n\
# safe to delete and is never part of the project.\n\
*\n";

/// The cache folder of the project in `project_root`. It may not exist yet.
pub fn cache_dir(project_root: &Path) -> PathBuf {
    project_root.join(CACHE_DIR)
}

/// Creates the cache folder and its ignore file if needed, and returns the
/// folder. An ignore file that differs from [`CACHE_IGNORE`] is rewritten.
pub fn ensure_cache_dir(project_root: &Path) -> Result<PathBuf, ProjectError> {
    let dir = cache_dir(project_root);
    let io = |path: &Path| {
        let path = path.to_path_buf();
        move |source| ProjectError::Io { path, source }
    };
    std::fs::create_dir_all(&dir).map_err(io(&dir))?;
    let ignore = dir.join(".gitignore");
    let current = match std::fs::read_to_string(&ignore) {
        Ok(text) => Some(text),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => None,
        Err(e) => return Err(io(&ignore)(e)),
    };
    if current.as_deref() != Some(CACHE_IGNORE) {
        std::fs::write(&ignore, CACHE_IGNORE).map_err(io(&ignore))?;
    }
    Ok(dir)
}
